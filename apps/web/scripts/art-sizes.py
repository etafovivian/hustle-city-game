"""Writes src/components/artSizes.ts: pixel size of every map sprite, so the map draws each at its own shape.
Run after adding art: python3 scripts/art-sizes.py"""
import glob, json, pathlib
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent
sizes = {}
for d in ("buildings", "props", "life", "nature", "landmarks", "transit"):
    for f in sorted((root / "public/art" / d).glob("*.webp")):
        sizes[f"/art/{d}/{f.name}"] = list(Image.open(f).size)
# Vector stand-ins (transit and landmarks, until their art arrives): the size is on the <svg> element.
import re
for d in ("transit", "landmarks"):
    for f in sorted((root / "public/art" / d).glob("*.svg")):
        m = re.search(r'<svg[^>]* width="([\d.]+)" height="([\d.]+)"', f.read_text())
        sizes[f"/art/{d}/{f.name}"] = [round(float(m.group(1))), round(float(m.group(2)))]
body = ",\n".join(f'  "{k}": [{w}, {h}]' for k, (w, h) in sizes.items())
(root / "src/components/artSizes.ts").write_text(
    "// Generated by scripts/art-sizes.py: [width, height] in pixels of each map sprite.\n"
    f"export const ART_SIZE: Record<string, [number, number]> = {{\n{body},\n}};\n"
)
print(len(sizes), "sprites")
