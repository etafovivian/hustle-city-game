// The plots for sale, exported from the city layout for the server (it prices and checks purchases with them).
// Run: node scripts/export-plots.ts        (writes packages/shared/src/plots.gen.ts)
//      node scripts/export-plots.ts --check (fails if the file is out of date; part of `pnpm test`)
import { readFileSync, writeFileSync } from "node:fs";
import { FOR_SALE } from "../src/components/cityLayout.ts";

const out = new URL("../../../packages/shared/src/plots.gen.ts", import.meta.url);
const rows = FOR_SALE.map((p) => `  ["${p.id}", "${p.area}", "${p.road}", ${p.hh}],`).join("\n");
const text = `// Generated by apps/web/scripts/export-plots.ts from the city layout. Do not edit by hand.
// Plots for sale: [id, area, frontage road, half-side in map units].
export const PLOTS_FOR_SALE: readonly (readonly [string, string, "arterial" | "collector" | "local" | "alley", number])[] = [
${rows}
];
`;
if (process.argv.includes("--check")) {
  let now = "";
  try {
    now = readFileSync(out, "utf8");
  } catch {
    /* missing */
  }
  if (now !== text) {
    console.error("plots.gen.ts is out of date: run node scripts/export-plots.ts");
    process.exit(1);
  }
  console.log(`plots up to date (${FOR_SALE.length})`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${FOR_SALE.length} plots`);
}
